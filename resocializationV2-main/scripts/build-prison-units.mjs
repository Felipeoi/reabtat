function cleanName(raw) {
  return raw
    .trim()
    .replace(/\*\*/g, '')
    .replace(/[\u201C\u201D\u201E\u201F\u2033\u2036]/g, '"')
    .replace(/[\u2018\u2019\u201A\u201B\u2032\u2035]/g, "'")
    .replace(/\s+/g, ' ')
    .trim();
}

function escapeSql(value) {
  return value.replace(/'/g, "''");
}

function isSeparator(line) {
  const trimmed = line.trim();
  return trimmed.length > 0 && /^\++$/.test(trimmed);
}

function isSectionHeader(name) {
  return SECTION_ONLY_PATTERNS.some((re) => re.test(name));
}

function isFacility(name) {
  if (isSectionHeader(name)) return false;
  return FACILITY_KEYWORDS.test(name);
}

function parseSource(content) {
  const units = [];
  let currentUf = null;

  for (const line of content.split('\n')) {
    if (isSeparator(line)) continue;

    const stateMatch = line.match(STATE_RE);
    if (stateMatch) {
      currentUf = stateMatch[1];
      continue;
    }

    if (!line.startsWith('\t')) continue;
    if (!currentUf) continue;

    const name = cleanName(line.replace(/^\t+/, ''));
    if (!name) continue;
    if (!isFacility(name)) continue;

    units.push({ name, uf_code: currentUf });
  }

  return units;
}

function buildSql(units) {
  const values = units
    .map(({ name, uf_code }) => `('${escapeSql(name)}', '${uf_code}')`)
    .join(',\n');

  return `-- Generated by scripts/build-prison-units.mjs — do not edit manually
INSERT INTO public.prison_units (name, uf_code) VALUES
${values}
ON CONFLICT (uf_code, name) DO NOTHING;
`;
}

function countByUf(units) {
  const counts = {};
  for (const { uf_code } of units) {
    counts[uf_code] = (counts[uf_code] || 0) + 1;
  }
  return counts;
}

function main() {
  const content = fs.readFileSync(SOURCE, 'utf8');
  const units = parseSource(content);
  const sql = buildSql(units);

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, sql, 'utf8');

  const byUf = countByUf(units);
  const sortedUfs = Object.keys(byUf).sort();

  console.log(`Generated: ${OUTPUT}`);
  console.log(`Total units: ${units.length}`);
  console.log('\nUnits per UF:');
  for (const uf of sortedUfs) {
    console.log(`  ${uf}: ${byUf[uf]}`);
  }
}

main();
